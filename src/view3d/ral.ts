export const ralCode = (value: string | undefined | null) => {
  const m = /(\d{4})/.exec(value ?? '')
  return m && RAL_CLASSIC[m[1]] ? m[1] : null
}

export const ralHex = (value: string | undefined | null) => {
  const code = ralCode(value)
  return code ? RAL_CLASSIC[code][0] : null
}

export const ralLabel = (code: string) => 'RAL ' + code
